/** the fixture pack, mounted from the in-memory jar and fully loaded + baked */
async function loadFixturePack(): Promise<ResourcePack> {
    const fileSystem = await ZipFileSystem.fromBuffer(vanillaShapedPackZip(), "e2e-fixture.jar");
    const pack = new ResourcePack(new PackVersion(PACK_FORMAT, 0));
    await pack.loadResources(fileSystem.getRootDirectories());
    return pack;
}

const E2E_BLOCK = Key.minecraft("e2e_block");
const E2E_STONE_TEXTURE = Key.minecraft("block/e2e_stone");
const E2E_UNUSED_TEXTURE = Key.minecraft("block/e2e_unused");

/**
 * The ordinals `TextureGallery#put(ResourcePool)` has to hand out for the fixture pack:
 * the missing-texture first, then the opaque textures in formatted-key order, then the
 * half-transparent ones in formatted-key order. None of this is the pool's own order —
 * the fixture writes its texture-entries scrambled on purpose.
 */
const EXPECTED_GALLERY_ORDER: readonly string[] = [
    "bluemap:block/missing",
    // opaque (getColorPremultiplied().a === 1)
    "minecraft:block/e2e_amber",
    "minecraft:block/e2e_fallback",
    "minecraft:block/e2e_lamp",
    "minecraft:block/e2e_stone",
    // half-transparent (getColorPremultiplied().a < 1)
    "minecraft:block/e2e_glass",
    "minecraft:block/e2e_water",
];

describe("Proof 1 — a block resolves end-to-end over a synthetic vanilla-shaped pack", () => {
    it("matches a Variants condition, and matches nothing when the condition cannot hold", async () => {
        const pack = await loadFixturePack();

        const resource = pack.getBlockStates().get(E2E_BLOCK);
        expect(resource).not.toBeNull();

        const variants = resource!.getVariants();
        expect(variants).not.toBeNull();
        // the fixture declares no "" / "default" member, so nothing can fall through
        expect(variants!.getDefaultVariant()).toBeNull();
        expect(variants!.getVariants().length).toBe(2);

        // lit=true selects the single-variant set …
        const litSelection = selectAt(resource!, worldBlock("e2e_block", { lit: "true" }), 0, 0, 0);
        expect(litSelection.length).toBe(1);
        expect(litSelection[0]!.getModel().getFormatted()).toBe("minecraft:block/e2e_block_lit");

        // … and a block that carries no `lit` property at all matches neither condition
        expect(selectAt(resource!, worldBlock("e2e_block"), 0, 0, 0)).toEqual([]);
    });

    it("selects a weighted variant by position, deterministically", async () => {
        const pack = await loadFixturePack();
        const resource = pack.getBlockStates().get(E2E_BLOCK)!;
        const unlit = worldBlock("e2e_block", { lit: "false" });

        // the fixture's lit=false set holds weights 1 and 3 (total 4), so
        // VariantSet#forEach picks the first variant exactly when hashToFloat < 0.25
        expect(hashToFloat(0, 0, 0)).toBeLessThan(0.25);
        expect(hashToFloat(0, 0, 1)).toBeGreaterThanOrEqual(0.25);

        const atOrigin = selectAt(resource, unlit, 0, 0, 0);
        expect(atOrigin.length).toBe(1);
        expect(atOrigin[0]!.getModel().getFormatted()).toBe("minecraft:block/e2e_block");

        const atNeighbour = selectAt(resource, unlit, 0, 0, 1);
        expect(atNeighbour.length).toBe(1);
        expect(atNeighbour[0]!.getModel().getFormatted()).toBe("minecraft:block/e2e_block_alt");

        // the same coordinate always yields the same variant — it is a position-hash, not a prng
        expect(selectAt(resource, unlit, 0, 0, 0)[0]).toBe(atOrigin[0]);
        expect(selectAt(resource, unlit, 0, 0, 1)[0]).toBe(atNeighbour[0]);
    });

    it("resolves the selected variant's model through a two-level parent chain", async () => {
        const pack = await loadFixturePack();
        const resource = pack.getBlockStates().get(E2E_BLOCK)!;

        const variant = selectAt(resource, worldBlock("e2e_block", { lit: "false" }), 0, 0, 0)[0]!;
        const model = variant.getModel().getResource((key) => pack.getModels().get(key));
        expect(model).not.toBeNull();

        // applyParent nulls the parent-path as it walks, so a baked model has none left
        expect(model!.getParent()).toBeNull();

        // one level up (block/cube_all): the element and the "particle" variable
        expect(model!.getElements()).not.toBeNull();
        expect(model!.getElements()!.length).toBe(1);
        expect(model!.getTextures().has("particle")).toBe(true);

        // two levels up (block/block): a variable and an ambientocclusion that only the
        // grandparent declares — they can only be here if applyParent recursed
        expect(model!.getTextures().has("fallback_only")).toBe(true);
        expect(model!.isAmbientocclusion()).toBe(false);

        // calculateProperties then found six faces backed by an opaque texture
        expect(model!.isOccluding()).toBe(true);
        expect(model!.isCulling()).toBe(true);
    });

    it("follows the #reference texture-variable indirection to the real texture pixels", async () => {
        const pack = await loadFixturePack();
        const resource = pack.getBlockStates().get(E2E_BLOCK)!;
        const variant = selectAt(resource, worldBlock("e2e_block", { lit: "false" }), 0, 0, 0)[0]!;
        const model = variant.getModel().getResource((key) => pack.getModels().get(key))!;

        // as parsed, "all" really is a reference to "tinted" — the indirection below is
        // not an artefact of the fixture already holding a path
        const asParsed = Model.Adapter.read(parse(E2E_BLOCK_MODEL_JSON));
        const parsedAll = asParsed.getTextures().get("all")!;
        expect(parsedAll.isReference()).toBe(true);
        expect(parsedAll.getReferenceName()).toBe("tinted");
        expect(parsedAll.getTexturePath()).toBeNull();

        // the face names "#all", which has to hop "all" -> "#tinted" -> "tinted"
        const face = model.getElements()![0]!.getFaces().get(Direction.UP);
        expect(face).toBeDefined();

        const texturePath = face!
            .getTexture()
            .getTexturePath((name) => model.getTextures().get(name) ?? null);
        expect(texturePath).not.toBeNull();
        expect(texturePath!.getFormatted()).toBe("minecraft:block/e2e_stone");

        // it is the very ResourcePath object declared under "tinted": resolveTexturePath
        // assigns the referenced variable's own path, so identity proves the hop happened
        expect(texturePath).toBe(model.getTextures().get("tinted")!.getTexturePath());

        const texture = texturePath!.getResource((key) => pack.getTextures().get(key));
        expect(texture).not.toBeNull();
        expect(texture!.getKey().getFormatted()).toBe("minecraft:block/e2e_stone");

        // … and the decoded image is the one the fixture painted, marker pixels and all
        const decoded = texture!.getTextureImage();
        expect([decoded.width, decoded.height]).toEqual([16, 16]);
        expect(pixel(decoded, 0, 0)).toEqual(E2E_STONE_TOP_LEFT);
        expect(pixel(decoded, 15, 15)).toEqual(E2E_STONE_BOTTOM_RIGHT);
        expect(pixel(decoded, 8, 8)).toEqual(E2E_STONE_FIELD);
    });

    it("keeps a texture no model references out of the pool", async () => {
        const pack = await loadFixturePack();

        expect(pack.getTextures().get(E2E_STONE_TEXTURE)).not.toBeNull();
        expect(pack.getTextures().get(E2E_UNUSED_TEXTURE)).toBeNull();
    });
});

describe("Proof 1 — the TextureGallery over that pack", () => {
    it("gives ordinal 0 to bluemap:block/missing, then opaque-first and key-sorted", async () => {
        const pack = await loadFixturePack();

        const gallery = new TextureGallery();
        gallery.put(pack.getTextures());

        const written = JSON.parse(gallery.writeTexturesFile()) as { resourcePath: string }[];
        expect(written.map((texture) => texture.resourcePath)).toEqual(EXPECTED_GALLERY_ORDER);

        // the gallery's own lookup agrees with the document it wrote
        expect(gallery.get(Key.bluemap("block/missing"))).toBe(0);
        EXPECTED_GALLERY_ORDER.forEach((formatted, ordinal) => {
            expect(gallery.get(Key.parse(formatted))).toBe(ordinal);
        });

        // an unknown key falls back to the missing-texture's ordinal
        expect(gallery.get(E2E_UNUSED_TEXTURE)).toBe(0);
    });

    it("preserves every ordinal across a write -> read round trip", async () => {
        const pack = await loadFixturePack();

        const gallery = new TextureGallery();
        gallery.put(pack.getTextures());
        const document = gallery.writeTexturesFile();

        const reread = TextureGallery.readTexturesFile(document);

        EXPECTED_GALLERY_ORDER.forEach((formatted, ordinal) => {
            expect(reread.get(Key.parse(formatted))).toBe(ordinal);
        });

        // re-writing the re-read gallery lands every key back on the same index, which is
        // what a re-loaded resource-pack has to do for already-rendered tiles to keep
        // pointing at the textures they were rendered against
        const rewritten = JSON.parse(reread.writeTexturesFile()) as { resourcePath: string }[];
        expect(rewritten.map((texture) => texture.resourcePath)).toEqual(EXPECTED_GALLERY_ORDER);

        // note: the *animation* member deliberately does not survive the round trip —
        // upstream's writer and reader disagree, which is pinned bug-for-bug by
        // src/resources/pack/resourcepack/texture/Texture.test.ts. Only the ordinals are
        // claimed here.
    });
});

