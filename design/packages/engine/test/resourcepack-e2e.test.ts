// #region shared helpers

/** the rgba pixel at (x, y) of a decoded texture-image */
function pixel(image: PNG, x: number, y: number): Pixel {
    const i = (image.width * y + x) << 2;
    return [image.data[i]!, image.data[i + 1]!, image.data[i + 2]!, image.data[i + 3]!];
}

/** every variant the given resourcepack-blockstate selects for a world-block at (x, y, z) */
function selectAt(
    resource: PackBlockState,
    state: WorldBlockState,
    x: number,
    y: number,
    z: number,
): Variant[] {
    const selected: Variant[] = [];
    resource.forEach(state, x, y, z, (variant) => selected.push(variant));
    return selected;
}

function worldBlock(id: string, properties: Record<string, string> = {}): WorldBlockState {
    return new WorldBlockState(Key.minecraft(id), new Map(Object.entries(properties)));
}

