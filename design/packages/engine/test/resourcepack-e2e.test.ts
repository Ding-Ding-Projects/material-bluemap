// #region proof 2 — the live client-jar check (opt-in; skipped by default)

/** set to `1` to run the live proof at all */
const RUN_ENV = "BLUEMAP_E2E_DOWNLOAD";
/**
 * The accept-download consent flag, mirroring the core-config option of the same meaning.
 * Setting it asserts that the runner has accepted Mojang's EULA, owns a Minecraft (Java
 * Edition) licence, and agrees to BlueMap downloading a client file from Mojang's servers.
 * `MinecraftVersion#load` documents why it may never be defaulted to true, tests included.
 */
const CONSENT_ENV = "BLUEMAP_ACCEPT_DOWNLOAD";

const LIVE_VERSION = "1.21";
/** gitignored — see design/.gitignore. A Mojang jar is never committed. */
const CLIENT_JAR_CACHE = fileURLToPath(new URL("./.minecraft-client-cache/", import.meta.url));

const runRequested = process.env[RUN_ENV] === "1";
const consentGiven = process.env[CONSENT_ENV] === "1";

/**
 * The skip below only names itself under a reporter that prints individual test-titles;
 * the default one prints a bare "1 skipped". So the reason is also written to stdout at
 * collection-time, before any console-mock is installed — a proof that never ran must not
 * be mistakable for a proof that passed.
 */
if (!runRequested || !consentGiven) {
    console.info(
        `[resourcepack-e2e] Proof 2 (live Minecraft ${LIVE_VERSION} client-jar) DID NOT RUN. ` +
            `It is opt-in: set ${RUN_ENV}=1 and ${CONSENT_ENV}=1 to enable it. ` +
            `Proofs 1 and 3 ran offline as usual.`,
    );
}

/** a client-jar download plus a full vanilla pack load is minutes of work, not seconds */
const LIVE_TIMEOUT_MS = 20 * 60 * 1000;

describe("Proof 2 — a real Minecraft client-jar resolves minecraft:grass_block", () => {
    if (!runRequested || !consentGiven) {
        // A silently-skipped proof is worse than no proof, so the reason is in the title:
        // whoever reads the run output can tell "this passed" from "this never ran".
        it.skip(
            `SKIPPED, NEVER RAN — this proof downloads the real Minecraft ${LIVE_VERSION} client-jar ` +
                `from Mojang. To run it set BOTH ${RUN_ENV}=1 and ${CONSENT_ENV}=1 ` +
                `(${CONSENT_ENV}=1 means you accept Mojang's EULA and own a Minecraft Java Edition ` +
                `licence). Currently ${RUN_ENV}=${process.env[RUN_ENV] ?? "<unset>"}, ` +
                `${CONSENT_ENV}=${process.env[CONSENT_ENV] ?? "<unset>"}. ` +
                `See packages/engine/README.md.`,
            () => {
                // intentionally empty — this body never runs
            },
        );
        return;
    }

    it(
        `downloads the ${LIVE_VERSION} client-jar and resolves grass_block to real texture pixels`,
        async () => {
            await mkdir(CLIENT_JAR_CACHE, { recursive: true });

            // `true` here is the accept-download consent the runner gave via CONSENT_ENV.
            // The jar is cached under CLIENT_JAR_CACHE, so a rerun re-uses it.
            const version = await MinecraftVersion.load(LIVE_VERSION, CLIENT_JAR_CACHE, true);
            expect(version.getId()).toBe(LIVE_VERSION);

            // hand the loader the jar *path* — Pack#loadResourcePath mounts it itself,
            // exactly as it does for a jar the caller configured
            const cacheFs = new DirFileSystem(CLIENT_JAR_CACHE);
            const jar = cacheFs.getRoot().resolve(basename(version.getResourcePack()));
            expect(await jar.isRegularFile()).toBe(true);

            const pack = new ResourcePack(version.getResourcePackVersion());
            await pack.loadResources([jar]);

            const resource = pack.getBlockStates().get(Key.minecraft("grass_block"));
            expect(resource).not.toBeNull();

            const selected = selectAt(
                resource!,
                worldBlock("grass_block", { snowy: "false" }),
                0,
                0,
                0,
            );
            expect(selected.length).toBe(1);
            expect(selected[0]!.getModel().getFormatted()).toContain("grass_block");

            const model = selected[0]!.getModel().getResource((key) => pack.getModels().get(key));
            expect(model).not.toBeNull();
            expect(model!.getElements()).not.toBeNull();

            const faces = model!.getElements()![0]!.getFaces();
            expect(faces.size).toBeGreaterThan(0);

            let resolvedFaces = 0;
            for (const face of faces.values()) {
                const texturePath = face
                    .getTexture()
                    .getTexturePath((name) => model!.getTextures().get(name) ?? null);
                expect(texturePath).not.toBeNull();

                const texture = texturePath!.getResource((key) => pack.getTextures().get(key));
                expect(texture).not.toBeNull();

                // a real vanilla texture, not the bluemap missing-texture placeholder
                expect(texture!.getKey().getNamespace()).toBe(Key.MINECRAFT_NAMESPACE);

                const image = texture!.getTextureImage();
                expect(image.width).toBeGreaterThan(0);
                expect(image.height).toBeGreaterThan(0);
                expect(image.data.length).toBe(image.width * image.height * 4);

                resolvedFaces++;
            }
            expect(resolvedFaces).toBe(faces.size);
        },
        LIVE_TIMEOUT_MS,
    );
});

