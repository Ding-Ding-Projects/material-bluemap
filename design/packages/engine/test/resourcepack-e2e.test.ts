// #region proof 3 — the shape of textures.json

/**
 * Upstream's serialization contract for `textures.json`, read from the java source at
 * vendor/BlueMap (tag-free `main` tree, commit e664c1a):
 *
 *   core/…/map/TextureGallery.java
 *     - `GSON.toJson(textures, Texture[].class, writer)` — a BARE ARRAY indexed by ordinal,
 *       built with `ResourcesGson.addAdapter(new GsonBuilder())` plus
 *       `FieldNamingPolicy.IDENTITY`, so member-names are the java field-names verbatim.
 *   core/…/resources/pack/resourcepack/texture/Texture.java
 *     - `@SerializedName("resourcePath") private Key key` — the member is `resourcePath`,
 *       NOT `key`.
 *     - `private Color color`, `private boolean halfTransparent`, `private String texture`.
 *     - `@Nullable private AnimationMeta animation` — gson does not serialize nulls by
 *       default, so the member is OMITTED when there is no animation.
 *     - the texture-string is `TEXTURE_STRING_PREFIX + base64`, i.e. `data:image/png;base64,…`.
 *   core/…/resources/adapter/ColorAdapter.java
 *     - `write` calls `value.straight()` then emits `[r, g, b, a]` — a four-number array.
 *
 * THIS IS A SHAPE ASSERTION, NOT A DIFF AGAINST JAVA. No java output has been generated or
 * compared; there is no oracle yet (that is issue #3). Do not read a passing run here as
 * "matches BlueMap" — it says only that the document has the members upstream's gson would
 * emit, with the types it would emit them as.
 *
 * WHEN THE ORACLE LANDS: keep this block (a shape failure is a clearer diagnosis than a
 * byte diff) and add a sibling test that loads the java-produced `textures.json` for the
 * same pack and compares parsed element-for-element — resourcePath and ordinal exactly,
 * color within a float32 epsilon, and the decoded png pixel-for-pixel rather than by
 * base64 string, since two png encoders may disagree on chunk layout for identical pixels.
 */
describe("Proof 3 — textures.json has the shape upstream's gson would emit", () => {
    const TEXTURE_URI_PREFIX = "data:image/png;base64,";

    async function texturesJson(): Promise<unknown> {
        const pack = await loadFixturePack();
        const gallery = new TextureGallery();
        gallery.put(pack.getTextures());
        return JSON.parse(gallery.writeTexturesFile());
    }

    it("is a bare array indexed by ordinal, not an object", async () => {
        const document = await texturesJson();

        expect(Array.isArray(document)).toBe(true);
        expect((document as unknown[]).length).toBe(EXPECTED_GALLERY_ORDER.length);
    });

    it("carries resourcePath / color / halfTransparent / texture on every element", async () => {
        const elements = (await texturesJson()) as Record<string, unknown>[];

        for (const element of elements) {
            const members = Object.keys(element).sort();
            // `animation` is the only optional member; nothing else may appear
            expect(members.filter((name) => name !== "animation")).toEqual([
                "color",
                "halfTransparent",
                "resourcePath",
                "texture",
            ]);

            // the java field is `key`; the wire member is `resourcePath`
            expect(element["key"]).toBeUndefined();
            expect(typeof element["resourcePath"]).toBe("string");
            expect(Key.parse(element["resourcePath"] as string).getFormatted()).toBe(
                element["resourcePath"],
            );

            // ColorAdapter#write -> [r, g, b, a]. Four finite numbers is the whole
            // contract — gson writes raw floats, so no range is promised (and asserting
            // one would be a float-epsilon flake on a straight()-divided average).
            const color = element["color"];
            expect(Array.isArray(color)).toBe(true);
            expect((color as unknown[]).length).toBe(4);
            for (const channel of color as unknown[]) {
                expect(typeof channel).toBe("number");
                expect(Number.isFinite(channel as number)).toBe(true);
                expect(channel as number).toBeGreaterThanOrEqual(0);
            }

            expect(typeof element["halfTransparent"]).toBe("boolean");
            expect(typeof element["texture"]).toBe("string");
            expect(element["texture"] as string).toMatch(/^data:image\/png;base64,/);
        }
    });

    it("encodes the texture as a decodable data:image/png;base64 uri", async () => {
        const elements = (await texturesJson()) as Record<string, unknown>[];

        const stone = elements.find(
            (element) => element["resourcePath"] === "minecraft:block/e2e_stone",
        );
        expect(stone).toBeDefined();

        const uri = stone!["texture"] as string;
        const base64 = uri.substring(TEXTURE_URI_PREFIX.length);
        const bytes = Buffer.from(base64, "base64");
        // the png signature — the uri really holds png bytes, not an opaque blob
        expect([...bytes.subarray(0, 8)]).toEqual([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
    });

    it("omits `animation` when there is none, and emits it when there is", async () => {
        const elements = (await texturesJson()) as Record<string, unknown>[];

        const stone = elements.find(
            (element) => element["resourcePath"] === "minecraft:block/e2e_stone",
        )!;
        expect("animation" in stone).toBe(false);

        // the fixture gives block/e2e_lamp a sibling .png.mcmeta
        const lamp = elements.find(
            (element) => element["resourcePath"] === "minecraft:block/e2e_lamp",
        )!;
        expect("animation" in lamp).toBe(true);
        expect(lamp["animation"]).toEqual({
            interpolate: true,
            width: 1,
            height: 1,
            frametime: 3,
        });
    });
});

