/**
 * A marker set as BlueMap's API deserialises it.
 *
 * The set's own container fields are modelled; the markers inside it are passed
 * through untouched. Marker shapes are the markers contract's business, not the
 * config schema's, and half-modelling them here would produce an editor that
 * silently drops fields it did not know about.
 */
const markerSetSchema = z.looseObject({
    label: hoconString().default(""),
    toggleable: hoconBoolean().default(true),
    "default-hidden": hoconBoolean().default(false),
    sorting: hoconInt().default(0),
    markers: z.record(z.string(), z.unknown()).default({}),
});

export const mapConfigSchema = z.object({
    loader: namespacedKey().default("bluemap:anvil"),
    world: hoconString().nullable().default(null),
    dimension: namespacedKey().nullable().default(null),
    "dimension-type": namespacedKey().nullable().default(null),
    name: hoconString().nullable().default(null),
    sorting: hoconInt().default(0),
    "start-pos": vector2i().default({ x: 0, z: 0 }),
    "sky-color": hexColor().default("#7dabff"),
    "void-color": hexColor().default("#000000"),
    "sky-light": hoconNumber().default(1),
    "ambient-light": hoconNumber().default(0),
    "remove-caves-below-y": hoconInt().default(55),
    "cave-detection-ocean-floor": hoconInt().default(10000),
    "cave-detection-uses-block-light": hoconBoolean().default(false),
    "min-inhabited-time": hoconInt().default(0),
    "min-inhabited-time-radius": hoconInt().default(0),
    "render-mask": combinedMaskSchema.default([]),
    "render-edges": hoconBoolean().default(true),
    "edge-light-strength": hoconInt().default(15),
    "enable-perspective-view": hoconBoolean().default(true),
    "enable-flat-view": hoconBoolean().default(true),
    "enable-free-flight-view": hoconBoolean().default(true),
    "enable-hires": hoconBoolean().default(true),
    "check-for-removed-regions": hoconBoolean().default(true),
    storage: hoconString().default("file"),
    "ignore-missing-light-data": hoconBoolean().default(false),
    "marker-sets": z.record(z.string(), markerSetSchema).nullable().default(null),
    "hires-tile-size": hoconInt().default(32),
    "lowres-tile-size": hoconInt().default(500),
    "lod-count": hoconInt().default(3),
    "lod-factor": hoconInt().default(5),
});

