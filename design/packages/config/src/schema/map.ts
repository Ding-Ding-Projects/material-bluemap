/**
 * `maps/<id>.conf` — one file per map, and the file most worth getting right.
 *
 * This is where every setting that can invalidate an already-rendered map lives,
 * which is why each field carries {@link FieldMeta.invalidatesTiles}: the GUI has
 * to be able to say "saving this throws away 961 tiles and re-renders them"
 * before somebody clicks save, not afterwards.
 *
 * Java source: `common/src/main/java/de/bluecolored/bluemap/common/config/MapConfig.java`
 * Template:    `common/src/main/resources/de/bluecolored/bluemap/config/maps/map.conf`
 */

