/** A Java `LinkedHashSet<String>`: ordered, and duplicates collapse. */
function uniqueStringList(): z.ZodType<string[]> {
    return z.preprocess(
        (value) => (Array.isArray(value) ? Array.from(new Set(value.map((item) => (typeof item === "number" || typeof item === "boolean" ? String(item) : item)))) : value),
        z.array(z.string()),
    );
}

